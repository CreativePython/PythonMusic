"""Build a standalone executable from a student's script, using PyInstaller.

This is the engine behind the editor's "Create Executable" button
(``pem.editing.exebuilder`` is the thin Tk layer on top).  It is deliberately
separate from ``PEM/build.py`` -- that script builds the PEM *application*;
this one builds the *student's* program -- but it borrows the same recipe for
the hard case (bundle PySide6, the audio backend, and every PythonMusic module;
trim the large unused parts) from ``pem.build.packages``.

Two shapes of build, decided by whether the program uses PythonMusic:

* **Plain Python program.**  PyInstaller freezes the student's script directly,
  following and bundling exactly the imports it uses -- a small executable.  The
  program simply runs and exits like normal.

* **PythonMusic program.**  These need the whole PythonMusic stack (PySide6, the
  audio backend, every PythonMusic module), which those modules reach for
  dynamically in ways PyInstaller can't see -- so we force it all in, exactly as
  ``PEM/build.py`` does for the app.  The frozen entry point is a small
  *launcher* that:
    1. warms up the audio engine (if the program plays sound) so the first
       notes don't crackle;
    2. runs the student's *unmodified* script via ``runpy`` (so error messages
       still point at the student's real line numbers); and
    3. keeps the program alive afterwards -- a window program stays open until
       the person closes/quits it, and music plays to the end -- mirroring how
       PEM keeps a script running (see ``pem.execution.run.pump_gui_events``).

PyInstaller always runs as a child process so the student's "Cancel" button can
actually stop it.
"""

import os
import sys
import shutil
import platform
import subprocess
import tempfile
from pathlib import Path

from pem.build import packages


# PythonMusic's own top-level modules.  If a student's program imports any of
# these, we switch to the "batteries included" launcher build (see above).
PYTHONMUSIC_MODULES = {
   "music", "gui", "midi", "osc", "timer", "utilities",
   "iannix", "markov", "zipf", "image",
}

# Third-party packages that ship with PythonMusic.  Force-included alongside the
# PythonMusic modules, to cover the pieces those modules load dynamically.
# These are import names, not pip names.
RUNTIME_DEPENDENCIES = [
   "tinysoundfont",   # software synthesizer used for audio playback
   "sounddevice",     # audio output
   "soundfile",       # audio file reading/writing
   "rtmidi",          # MIDI backend (pip name: python-rtmidi)
   "osc4py3",         # OSC networking
   "regex",           # richer regular expressions
]

# The launcher that becomes the frozen entry point for PythonMusic programs.
# The __PEM_* tokens are filled in by _write_launcher (plain text replacement,
# so the template can contain its own braces freely).
_LAUNCHER_TEMPLATE = '''\
"""Launcher generated by PEM's "Create Executable" feature.

Runs the bundled PythonMusic program, then keeps it alive the way PEM does:
music plays to the end, and a window program stays open until it is finished.
"""
import os
import sys
import runpy
import threading

# Build setting: quit once the last window closes?  Off by default, because some
# PythonMusic features (e.g. MidiIn's device chooser) open and close a window
# while the program keeps running.  On suits a typical single-window program.
_QUIT_ON_WINDOW_CLOSE = __PEM_QUIT_ON_CLOSE__

# How many program windows are currently open (only tracked when the setting is
# on).  Updated as windows open and close so we know when the last one is gone.
_open_windows = {"count": 0, "opened_any": False}
_open_windows_lock = threading.Lock()


def _bundled_script_path():
   """Locate the student's script inside the frozen bundle."""
   base = getattr(sys, "_MEIPASS", os.path.dirname(os.path.abspath(__file__)))
   return os.path.join(base, __PEM_SCRIPT_NAME__)


def _watch_windows_for_quit():
   """Track open windows so the program can quit once the last one closes.

   Wraps Display creation to count each window and register a close callback
   (via the handler's registerEvent, which reliably makes the renderer report
   closes -- both the close box and Display.close()).  Only called when the
   "quit on last window" setting is on.
   """
   try:
      import gui
   except Exception:
      return

   _original_init = gui.Display.__init__

   def _counting_init(self, *args, **kwargs):
      _original_init(self, *args, **kwargs)
      with _open_windows_lock:
         _open_windows["count"] += 1
         _open_windows["opened_any"] = True

      def _on_close():
         with _open_windows_lock:
            _open_windows["count"] -= 1

      try:
         gui._handler().registerEvent(self._objectId, "displayClose", _on_close)
      except Exception:
         pass

   gui.Display.__init__ = _counting_init


def _all_windows_closed():
   """True once at least one window has opened and all of them have closed."""
   with _open_windows_lock:
      return _open_windows["opened_any"] and _open_windows["count"] <= 0


def _warm_up_audio():
   """Prepare the audio engine so the program's first moment doesn't crackle.

   A frozen executable has a much busier startup than a normal Python run
   (it unpacks and loads everything from the bundle), which can starve the
   synthesizer's small default audio buffer for a moment -- heard as a burst of
   gritty sound at the start.  Give the synthesizer a larger, more forgiving
   buffer *before* it opens the audio stream, then let it settle.  This only
   happens in the built program, so PEM and plain ``python`` runs are unchanged.
   """
   try:
      import tinysoundfont
      _original_start = tinysoundfont.Synth.start

      # The synth applies each scheduled note at the next audio-buffer boundary,
      # so the buffer size doubles as the timing grid: too large and note starts
      # get audibly quantized ("swung").  Pick the smallest buffer that still
      # rides out the frozen app's busy startup -- a modest bump over the tiny
      # default (1024), not a big one.
      def _start_with_larger_buffer(self, buffer_size=2048, **kwargs):
         return _original_start(self, buffer_size=buffer_size, **kwargs)

      # music.py starts the synth with the default buffer size, so raising the
      # default here is enough -- no change to PythonMusic needed.
      tinysoundfont.Synth.start = _start_with_larger_buffer
   except Exception:
      pass

   try:
      import music        # noqa: F401  (starts the synth, now with a bigger buffer)
      import time
      # Let the frozen app finish its busy startup before the program plays, so
      # the modest buffer above is enough to avoid under-runs.
      time.sleep(1.0)
   except Exception:
      pass


def _keep_program_alive():
   """Block until the program is genuinely finished.

   Windows live in PythonMusic's separate renderer process, which owns the Qt
   event loop and the Dock icon; music finishes when its scheduled timers drain.
   """
   import time
   _timer = sys.modules.get("timer")
   _gui = sys.modules.get("gui")
   _handler = getattr(_gui, "_GUI_HANDLER", None) if _gui is not None else None
   _child = getattr(_handler, "childProcess", None) if _handler is not None else None

   def _music_playing():
      return bool(getattr(_timer, "_activeTimers", [])) if _timer is not None else False

   def _window_open():
      if _child is None:
         return False
      try:
         return _child.is_alive()
      except Exception:
         return False

   # A window program: the window (and its Dock icon) live in PythonMusic's
   # separate renderer process, which runs its own Qt event loop.  This process
   # only has to stay alive alongside it -- and must NOT start its own
   # QApplication, or the app would show a second Dock icon.
   #
   # By default we stay up until the person quits the app (the renderer process
   # ends), because some features keep running after a window closes.  When the
   # "quit on last window" setting is on, we instead stop once the program's last
   # window has closed and any music has finished.
   if _child is not None:
      try:
         while _window_open():
            if _QUIT_ON_WINDOW_CLOSE and _all_windows_closed() and not _music_playing():
               break
            time.sleep(0.1)
      except KeyboardInterrupt:
         pass
      return

   # A music-only (or non-visual) program: run a real Qt event loop so this
   # process stays responsive (its Dock icon settles instead of bouncing) and
   # stop once the scheduled notes have all played.
   try:
      from PySide6 import QtWidgets, QtCore
   except Exception:
      QtWidgets = None

   if QtWidgets is not None:
      app = QtWidgets.QApplication.instance() or QtWidgets.QApplication(sys.argv)
      started = time.time()

      def _check():
         # Brief grace so we don't stop before the program schedules its notes.
         if time.time() - started < 0.3:
            return
         if not _music_playing():
            app.quit()

      ticker = QtCore.QTimer()
      ticker.timeout.connect(_check)
      ticker.start(150)
      app.exec()
      return

   # Fallback if Qt somehow isn't available.
   try:
      time.sleep(0.2)
      while _music_playing():
         time.sleep(0.1)
   except KeyboardInterrupt:
      pass


def main():
   __PEM_WARM_UP__
   if _QUIT_ON_WINDOW_CLOSE:
      _watch_windows_for_quit()

   scriptPath = _bundled_script_path()
   scriptDir = os.path.dirname(scriptPath)
   if scriptDir and scriptDir not in sys.path:
      sys.path.insert(0, scriptDir)

   # Run the student's program as if launched directly (it is __main__, on its
   # own real file, so tracebacks read naturally).
   try:
      runpy.run_path(scriptPath, run_name="__main__")
   except SystemExit:
      return

   _keep_program_alive()


if __name__ == "__main__":
   # PythonMusic opens windows in a spawned child process; freeze_support routes
   # those children to their own work instead of re-running this launcher.
   import multiprocessing
   multiprocessing.freeze_support()
   main()
'''


class BuildResult:
   """Outcome of a build attempt, returned to the Tk layer for display.

   Attributes:
      success (bool): True if an executable was produced.
      output_path (Path or None): The finished executable / app / archive.
      message (str): A student-friendly explanation of the result.
      cancelled (bool): True if the student cancelled the build.
      external_imports (list): Third-party imports we did not bundle, if any.
   """

   def __init__(self, success, output_path=None, message="",
                cancelled=False, external_imports=None):
      self.success = success
      self.output_path = output_path
      self.message = message
      self.cancelled = cancelled
      self.external_imports = external_imports or []


def build_user_executable(script_path, console=False, quit_on_window_close=False,
                          progress=None, cancel_event=None):
   """Build a standalone executable from ``script_path``.

   Args:
      script_path: Path to the student's ``.py`` file (already saved to disk).
      console (bool): Build a console executable (a terminal window is attached,
         so ``print()`` and ``input()`` work).  When False the program runs
         windowed, with no console -- fine for GUI/audio programs that never
         read typed input.  Comes from the "Show Console" preference.
      quit_on_window_close (bool): For a window program, end the program once its
         last window closes.  Off by default (some features keep running after a
         window closes).  Comes from the "Quit When Last Window Closes" preference.
      progress (callable or None): Called with a short status string as the
         build moves through its stages, for the progress dialog.
      cancel_event (threading.Event or None): If set mid-build, the PyInstaller
         child process is terminated and a cancelled result is returned.

   Returns:
      BuildResult
   """
   report = progress if progress is not None else (lambda message: None)

   scriptPath = Path(script_path).resolve()
   scriptDir = scriptPath.parent
   scriptName = scriptPath.stem

   # Everything transient (spec file, work folder, generated launcher) goes in
   # one temp dir we delete at the end.
   tempDir = Path(tempfile.mkdtemp(prefix="pem_build_"))

   try:
      report("Looking at your program...")
      usedModules = _imports_including_siblings(scriptPath, scriptDir) & PYTHONMUSIC_MODULES
      usesPythonMusic = bool(usedModules)
      playsAudio = "music" in usedModules
      usesWindows = "gui" in usedModules
      externalImports = _classify_imports(scriptPath, scriptDir)
      siblingModules = _find_local_modules(scriptPath, scriptDir)

      report("Preparing the build...")
      specPath = _write_spec(
         tempDir=tempDir,
         scriptPath=scriptPath,
         scriptName=scriptName,
         console=console,
         usesPythonMusic=usesPythonMusic,
         playsAudio=playsAudio,
         # The quit-on-close behaviour only matters for programs with windows.
         quitOnWindowClose=quit_on_window_close and usesWindows,
         siblingModules=siblingModules,
         externalImports=externalImports,
      )

      report("Building the executable (this can take a few minutes)...")
      # Build into the temp folder, not the student's folder: PyInstaller's
      # macOS build leaves an intermediate onedir folder next to the .app, and
      # we don't want that clutter landing beside the student's script.  We move
      # just the finished result out afterwards.
      built, buildLog = _run_pyinstaller(
         specPath=specPath,
         distDir=tempDir / "dist",
         workDir=tempDir / "build",
         cancel_event=cancel_event,
      )

      if cancel_event is not None and cancel_event.is_set():
         return BuildResult(False, cancelled=True)

      if not built:
         return BuildResult(
            False,
            message=_friendly_failure(externalImports, buildLog),
            external_imports=externalImports,
         )

      report("Finishing up...")
      shareablePath, message = _collect_output(
         tempDir / "dist", scriptDir, scriptName)
      if shareablePath is None:
         return BuildResult(
            False,
            message=_friendly_failure(externalImports, buildLog),
            external_imports=externalImports,
         )

      return BuildResult(True, output_path=shareablePath, message=message,
                         external_imports=externalImports)

   finally:
      # The finished executable lives in the student's folder, not here, so the
      # whole temp tree is safe to remove.  Cleanup failures are non-fatal.
      try:
         shutil.rmtree(tempDir, ignore_errors=True)
      except Exception:
         pass


# ── Import analysis ────────────────────────────────────────────────────────────

def _script_imports(scriptPath):
   """Return the set of top-level module names imported by one script.

   Uses the AST so it understands ``import a.b`` and ``from a import b``.
   Returns an empty set if the file can't be read or parsed -- import analysis
   is advisory, so a parse failure must never block a build.
   """
   import ast

   names = set()
   try:
      source = Path(scriptPath).read_text(encoding="utf-8")
      tree = ast.parse(source)
   except Exception:
      return names

   for node in ast.walk(tree):
      if isinstance(node, ast.Import):
         for alias in node.names:
            names.add(alias.name.split(".")[0])
      elif isinstance(node, ast.ImportFrom):
         if node.module and node.level == 0:
            names.add(node.module.split(".")[0])
   return names


def _imports_including_siblings(scriptPath, scriptDir):
   """Return imports of the script *and* of any sibling files it imports.

   A student may ``import music`` from a helper file rather than their main
   script, so we look one level into sibling modules too before deciding whether
   the program uses PythonMusic.
   """
   allImports = set(_script_imports(scriptPath))
   for name in list(allImports):
      sibling = scriptDir / f"{name}.py"
      if sibling.exists() and sibling != scriptPath:
         allImports |= _script_imports(sibling)
      package_init = scriptDir / name / "__init__.py"
      if package_init.exists():
         allImports |= _script_imports(package_init)
   return allImports


def _classify_imports(scriptPath, scriptDir):
   """Return third-party imports that are neither PythonMusic nor a sibling file.

   If a build fails, these are the most likely culprit, so we surface them in
   the failure message.
   """
   bundled = set(PYTHONMUSIC_MODULES) | set(RUNTIME_DEPENDENCIES)
   for name in packages.CORE_LIBRARIES:
      bundled.add(name.split(".")[0])
   stdlib = set(sys.stdlib_module_names)

   external = []
   for name in sorted(_script_imports(scriptPath)):
      if name in bundled or name in stdlib:
         continue
      if (scriptDir / f"{name}.py").exists():
         continue
      if (scriptDir / name / "__init__.py").exists():
         continue
      external.append(name)
   return external


def _find_local_modules(scriptPath, scriptDir):
   """Find sibling ``.py`` files / packages the script imports, to bundle them.

   Returns a list of ``(name, is_package)`` tuples.  A student might split a
   project across a few files that sit next to the script; those must ride along
   in the executable.
   """
   siblings = []
   for name in _script_imports(scriptPath):
      package = scriptDir / name
      if package.is_dir() and (package / "__init__.py").exists():
         siblings.append((name, True))
         continue
      module = scriptDir / f"{name}.py"
      if module.exists() and module != scriptPath:
         siblings.append((name, False))
   return siblings


# ── Launcher for PythonMusic programs ──────────────────────────────────────────

def _write_launcher(tempDir, scriptName, playsAudio, quitOnWindowClose):
   """Write the launcher that becomes the frozen entry point, and return its path.

   ``scriptName`` is the student's filename (e.g. ``furElise.py``); the launcher
   finds it in the bundle and runs it.  ``playsAudio`` decides whether to warm up
   the audio engine first; ``quitOnWindowClose`` decides whether the program ends
   when its last window closes.
   """
   warmUpCall = "_warm_up_audio()" if playsAudio else "pass"
   content = (
      _LAUNCHER_TEMPLATE
      .replace("__PEM_SCRIPT_NAME__", repr(scriptName))
      .replace("__PEM_WARM_UP__", warmUpCall)
      .replace("__PEM_QUIT_ON_CLOSE__", "True" if quitOnWindowClose else "False")
   )
   launcherPath = tempDir / "_pem_launcher.py"
   launcherPath.write_text(content, encoding="utf-8")
   return launcherPath


# ── Spec generation (mirrors PEM/build.py's recipe, for a user script) ─────────

def _locate_libportaudio():
   """Return the bundled PortAudio library path, if this platform ships one.

   PythonMusic bundles ``libportaudio`` (macOS) so audio output works without a
   system install; ``PEM/build.py`` bundles it for the app the same way.  In a
   pip / frozen install it lives inside the installed ``PythonMusic`` package.
   """
   try:
      import PythonMusic
   except Exception:
      return None
   binDir = Path(PythonMusic.__file__).parent / "bin"
   for candidate in ("libportaudio.2.dylib",):
      libPath = binDir / candidate
      if libPath.exists():
         return libPath
   return None


def _locate_soundfont():
   """Return a soundfont (.sf2) file to bundle, or None if none is found.

   Mirrors how ``music.py``'s ``_findSoundfont`` searches at runtime, so we
   bundle the same soundfont the student already uses.  Bundling it means a
   program that plays MIDI still has sound on a computer that has never run
   PythonMusic -- otherwise ``music.py`` falls back to *prompting* for a
   download, which a windowed executable (no console) can't answer.
   """
   candidates = []

   fromEnv = os.getenv("CREATIVEPYTHON_SOUNDFONT")
   if fromEnv:
      candidates.append(Path(fromEnv))

   home = Path.home()
   candidates += [home / "Soundfonts", home / "soundfonts"]

   # The usual location: PythonMusic's download cache.
   try:
      from platformdirs import user_data_dir
      candidates.append(Path(user_data_dir("PythonMusic", "CofC")) / "Soundfonts")
   except Exception:
      pass

   # If PEM itself is frozen, it may carry a bundled soundfont.
   if hasattr(sys, "_MEIPASS"):
      candidates.append(Path(sys._MEIPASS) / "soundfonts")

   for candidate in candidates:
      try:
         if candidate.is_file() and candidate.suffix.lower() == ".sf2":
            return candidate
         if candidate.is_dir():
            found = list(candidate.glob("*.sf2")) + list(candidate.glob("*.SF2"))
            if found:
               return found[0]
      except Exception:
         pass
   return None


def _write_spec(tempDir, scriptPath, scriptName, console, usesPythonMusic,
                playsAudio, quitOnWindowClose, siblingModules, externalImports):
   """Write a PyInstaller ``.spec`` for the student's program and return its path.

   For a PythonMusic program the entry point is the generated launcher, the
   student's script rides along as data (the launcher runs it), and the whole
   PythonMusic stack plus the audio library are forced in.  For a plain program
   PyInstaller freezes the student's script directly and follows its own
   imports.  Either way the large unused parts are excluded (see
   ``packages.getExcludes``), and the executable shape is chosen per platform:
   a ``.app`` on macOS, a single file elsewhere.
   """
   scriptDir = scriptPath.parent
   excludes = packages.getExcludes(profile="user_script")

   if usesPythonMusic:
      entryPath = _write_launcher(tempDir, scriptPath.name, playsAudio,
                                  quitOnWindowClose)
      # The launcher runs the student's script from the bundle, so the script
      # travels as data rather than as an analysed entry point.
      datas = [(str(scriptPath), ".")]
      # Force in everything PythonMusic reaches for dynamically, the sibling
      # files this program imports, and any third-party packages it uses.
      hiddenimports = list(packages.CORE_LIBRARIES) + list(RUNTIME_DEPENDENCIES)
      hiddenimports += [name for name, _isPackage in siblingModules]
      hiddenimports += externalImports
      binaries = []
      libportaudio = _locate_libportaudio()
      if libportaudio is not None:
         binaries.append((str(libportaudio), "."))

      # Bundle the soundfont so MIDI programs have sound on any computer, not
      # just one that has already downloaded it.  music.py looks for it under
      # "soundfonts" in the bundle (its _MEIPASS/soundfonts candidate).
      if playsAudio:
         soundfont = _locate_soundfont()
         if soundfont is not None:
            datas.append((str(soundfont), "soundfonts"))
   else:
      # Plain program: freeze the script itself and let PyInstaller follow its
      # imports.
      entryPath = scriptPath
      datas = []
      hiddenimports = []
      binaries = []

   system = platform.system()
   if system == "Darwin":
      if console:
         # A console program on macOS: a .app bundle can't show a console when
         # double-clicked (Finder attaches no terminal).  Build a single
         # executable named ".command" instead -- macOS opens .command files in
         # Terminal on double-click, so print()/input() and the console appear.
         exeText = _ONEFILE_EXE_TEMPLATE.format(name=scriptName + ".command", console=True)
      else:
         exeText = _MACOS_EXE_TEMPLATE.format(name=scriptName, console=False)
   else:
      exeText = _ONEFILE_EXE_TEMPLATE.format(name=scriptName, console=console)

   specText = _SPEC_TEMPLATE.format(
      entry=repr(str(entryPath)),
      pathex=repr([str(scriptDir)]),
      binaries=repr(binaries),
      datas=repr(datas),
      hiddenimports=repr(hiddenimports),
      excludes=repr(excludes),
      exe_text=exeText,
   )

   specPath = tempDir / f"{scriptName}.spec"
   specPath.write_text(specText, encoding="utf-8")
   return specPath


