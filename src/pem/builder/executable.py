"""Create Executable: package a student's script into a standalone program.

This module is the whole "Create Executable" feature.  The editor's File menu
calls ``ExeBuilder``, which confirms with the student, shows a progress dialog
with a Cancel button, and reports the result.  The build itself is
``build_user_executable``, which runs on a worker thread and never touches Tk.

The build is deliberately separate from ``PEM/build.py`` -- that script builds
the PEM *application*; this one builds the *student's* program -- but it borrows
the same recipe for the hard case (bundle PySide6, the audio backend, and every
PythonMusic module; trim the large unused parts) from ``pem.builder.packages``.

Create Executable is offered only when PEM runs on a regular Python
installation (pip-installed, or from source).  The frozen PEM app leaves it out:
PyInstaller can't build from inside it, because the app's Python modules are
compiled into it rather than stored as files.

Two shapes of build, decided by whether the program uses PythonMusic:

* **Plain Python program.**  PyInstaller freezes the student's script directly,
  following and bundling exactly the imports it uses -- a small executable.  The
  program simply runs and exits like normal.

* **PythonMusic program.**  These need the whole PythonMusic stack (PySide6, the
  audio backend, every PythonMusic module), which those modules reach for
  dynamically in ways PyInstaller can't see -- so we force it all in, exactly as
  ``PEM/build.py`` does for the app.  The frozen entry point is a small
  *launcher* that:
    1. warms up the audio engine (if the program plays sound) so the first
       notes don't crackle;
    2. runs the student's *unmodified* script via ``runpy`` (so error messages
       still point at the student's real line numbers); and
    3. keeps the program alive afterwards -- a window program stays open until
       the person closes/quits it, and music plays to the end -- mirroring how
       PEM keeps a script running (see ``pem.execution.run.pump_gui_events``).

PyInstaller always runs as a child process so the student's "Cancel" button can
actually stop it.

Troubleshooting a build
-----------------------
When a build fails, a full record of it is saved to ``create-executable.log`` in
PythonMusic's log folder (on macOS, ``~/Library/Logs/PythonMusic``), and the
error message shows the file's path.  The record covers the settings used, which
Python ran the build, the folders searched for modules, where the audio library
and soundfont were found, the generated
``.spec`` file, the exact PyInstaller command, and PyInstaller's own output.
The log from the build before that is kept as ``create-executable.log.prev``.
A successful build leaves no log behind.

For development, set the ``PEM_BUILD_DEBUG`` environment variable before
launching PEM:

    PEM_BUILD_DEBUG=1 pem              # pip-installed PEM
    PEM_BUILD_DEBUG=1 python -m pem    # PEM run from source

With it set, every build saves its log (not just failed ones), each step is also
printed to the terminal, PyInstaller runs with its most detailed logging, and
the temporary work folder -- holding the generated ``.spec`` file and launcher --
is kept instead of deleted (its location is in the log).
"""

