# ── Running PyInstaller as a cancellable child process ─────────────────────────

def _pyinstaller_command(specPath, distDir, workDir):
   """Build the command that runs PyInstaller on ``specPath``.

   Uses the current interpreter's PyInstaller (``-m PyInstaller``), so
   ``sys.executable`` must be a regular Python interpreter -- one reason the
   frozen PEM app doesn't offer Create Executable.
   """
   command = [
      sys.executable, "-m", "PyInstaller",
      str(specPath),
      "--distpath", str(distDir),
      "--workpath", str(workDir),
      "--noconfirm",
      "--clean",
   ]
   if DEBUG:
      # PyInstaller's most detailed output, showing why it made each choice.
      command += ["--log-level", "DEBUG"]
   return command


def _run_pyinstaller(specPath, distDir, workDir, log, cancel_event=None):
   """Run PyInstaller as a child process, watching for cancellation.

   Returns ``(success, output)`` where ``output`` is PyInstaller's combined
   output (used to explain failures).  If ``cancel_event`` is set while the
   build runs, the child process is terminated and ``success`` is False.  The
   command and its exit code are recorded in ``log``.
   """
   command = _pyinstaller_command(specPath, distDir, workDir)
   log.note("running: " + shlex.join(command))

   process = subprocess.Popen(
      command,
      stdout=subprocess.PIPE,
      stderr=subprocess.STDOUT,
      text=True,
   )

   outputLines = []
   # Drain output line by line so a cancel request is noticed promptly rather
   # than only after the (multi-minute) build finishes.
   while True:
      if cancel_event is not None and cancel_event.is_set():
         log.note("stopping PyInstaller because the build was cancelled")
         _terminate(process)
         return False, "".join(outputLines)
      line = process.stdout.readline()
      if line:
         outputLines.append(line)
         continue
      if process.poll() is not None:
         break

   returnCode = process.wait()
   log.note(f"PyInstaller exited with code {returnCode}")
   return returnCode == 0, "".join(outputLines)


def _terminate(process):
   """Stop a running PyInstaller child process, escalating if it lingers."""
   try:
      process.terminate()
      try:
         process.wait(timeout=5)
      except subprocess.TimeoutExpired:
         process.kill()
   except Exception:
      pass


# ── Locating and packaging the result ──────────────────────────────────────────

def _collect_output(distDir, scriptDir, scriptName):
   """Move the finished program into the student's folder.

   Returns ``(shareable_path, message)`` describing what was produced, or
   ``(None, "")`` if nothing was built.  On macOS this leaves the runnable
   ``.app`` plus a ``.tar.gz`` to share (a plain ``.zip`` loses the executable
   permissions and symlinks a Mac app needs, so the app would be broken -- the
   same reason ``PEM/build.py`` distributes a tar.gz).  On Windows/Linux it
   leaves the single executable file.
   """
   system = platform.system()

   if system == "Darwin":
      # A windowed program builds a .app; a console program builds a .command
      # single-file executable (opens in Terminal on double-click).
      builtApp = distDir / f"{scriptName}.app"
      builtCommand = distDir / f"{scriptName}.command"

      if builtApp.exists():
         appPath = scriptDir / f"{scriptName}.app"
         _replace_path(appPath, builtApp)
         _adhoc_codesign(appPath)
         archivePath = _make_tar_gz(scriptDir, f"{scriptName}.app",
                                    scriptDir / f"{scriptName}.tar.gz")
         message = (
            "Your program is ready.\n\n"
            f"To run it now:  {appPath.name}\n"
            f"To share it:    {archivePath.name if archivePath else appPath.name}\n\n"
            "Others can unpack the .tar.gz and run the app -- sharing it this way "
            "keeps the app working on their Mac."
         )
         return (archivePath or appPath), message

      if builtCommand.exists():
         commandPath = scriptDir / f"{scriptName}.command"
         _replace_path(commandPath, builtCommand)
         # Make sure it stays runnable (double-click in Finder needs the
         # executable bit; tar.gz below preserves it for sharing).
         try:
            commandPath.chmod(commandPath.stat().st_mode | 0o111)
         except Exception:
            pass
         archivePath = _make_tar_gz(scriptDir, commandPath.name,
                                    scriptDir / f"{scriptName}.tar.gz")
         message = (
            "Your program is ready.\n\n"
            f"To run it now:  double-click {commandPath.name} (it opens in Terminal)\n"
            f"To share it:    {archivePath.name if archivePath else commandPath.name}\n\n"
            "The Terminal window is where the program prints and reads typed input."
         )
         return (archivePath or commandPath), message

      return None, ""

   # Windows / Linux: a single executable file, already shareable as-is.
   builtExe = distDir / (f"{scriptName}.exe" if system == "Windows" else scriptName)
   if not builtExe.exists():
      return None, ""
   exePath = scriptDir / builtExe.name
   _replace_path(exePath, builtExe)
   message = (
      "Your program is ready.\n\n"
      f"{exePath}\n\n"
      "You can share this file with others using the same kind of computer."
   )
   return exePath, message


def _replace_path(destination, source):
   """Move ``source`` to ``destination``, replacing anything already there."""
   if destination.exists():
      if destination.is_dir():
         shutil.rmtree(destination, ignore_errors=True)
      else:
         destination.unlink()
   shutil.move(str(source), str(destination))


def _adhoc_codesign(appPath):
   """Ad-hoc sign a macOS ``.app`` to reduce Gatekeeper friction when shared.

   This is the same step ``PEM/build.py`` does; it avoids the "app is damaged"
   error.  Best-effort: a signing failure must not fail the whole build.
   """
   try:
      subprocess.run(
         ["codesign", "--deep", "--force", "--sign", "-", str(appPath)],
         stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, check=False,
      )
   except Exception:
      pass


def _make_tar_gz(sourceDir, memberName, archivePath):
   """Create ``archivePath`` as a gzip tar of ``memberName`` inside ``sourceDir``.

   Uses ``tar`` (like ``PEM/build.py``) so the app's executable permissions and
   internal symlinks survive -- a plain zip does not preserve these, which is
   what left the shared app broken.  Returns the archive path, or None on
   failure (the student still has the runnable ``.app``).
   """
   try:
      if archivePath.exists():
         archivePath.unlink()
      subprocess.run(
         ["tar", "-czf", str(archivePath), "-C", str(sourceDir), memberName],
         check=True,
      )
      return archivePath
   except Exception:
      return None
